/**
 * Runtime SEO for a static SPA.
 *
 * The site is a client-rendered Vite SPA on Vercel with no SSR, so there is no
 * server render in which to bake per-locale <head> tags. This composable keeps
 * the document head in sync with the active route and locale:
 *
 *   - <title> and <meta name="description">
 *   - <link rel="canonical">
 *   - <link rel="alternate" hreflang="…"> for every locale, plus x-default
 *   - Open Graph title / description / locale / alternate locales
 *   - <html lang> and <html dir>
 *
 * The origin is read from `location.origin` rather than hardcoded, so the tags
 * are correct on preview deployments, on a custom domain, and in local dev
 * without inventing a production URL the repository never declares.
 *
 * `scripts/prerender-seo.mjs` additionally writes a static copy of the
 * alternate links into every built HTML file, so crawlers that do not execute
 * JavaScript still see the full hreflang cluster.
 */

import { watchEffect } from "vue";
import { useRoute } from "vue-router";
import { useI18n } from "vue-i18n";
import { DEFAULT_LOCALE, LOCALES, getLocale } from "../i18n/locales.js";
import { pathFor } from "../router.js";

/** Finds or creates a <meta> tag and sets its content. */
function setMeta(attribute, key, content) {
  if (typeof document === "undefined") return;
  let tag = document.head.querySelector(`meta[${attribute}="${key}"]`);
  if (!tag) {
    tag = document.createElement("meta");
    tag.setAttribute(attribute, key);
    document.head.appendChild(tag);
  }
  tag.setAttribute("content", content);
}

/** Removes every tag previously generated by this module. */
function clearManaged(selector) {
  if (typeof document === "undefined") return;
  document.head.querySelectorAll(`${selector}[data-i18n-managed]`).forEach((node) => node.remove());
}

/** Appends a managed <link> tag. */
function addLink(rel, href, hreflang) {
  if (typeof document === "undefined") return;
  const link = document.createElement("link");
  link.setAttribute("rel", rel);
  link.setAttribute("href", href);
  if (hreflang) link.setAttribute("hreflang", hreflang);
  link.setAttribute("data-i18n-managed", "");
  document.head.appendChild(link);
}

export function useSeo() {
  const route = useRoute();
  const { t, locale } = useI18n();

  watchEffect(() => {
    if (typeof document === "undefined") return;

    const metaKey = route.meta?.metaKey ?? "home";
    const page = route.meta?.page ?? "home";
    const active = getLocale(locale.value) ?? getLocale(DEFAULT_LOCALE);
    const origin = typeof location !== "undefined" ? location.origin : "";

    const pageTitle = t(`meta.${metaKey}.title`);
    const description = t(`meta.${metaKey}.description`);

    // The home page uses the full brand headline rather than "Home — Brand".
    document.title =
      page === "home"
        ? `${t("meta.siteName")} — ${pageTitle}`
        : t("meta.titleTemplate", { page: pageTitle });

    setMeta("name", "description", description);

    // Open Graph.
    setMeta("property", "og:title", page === "home" ? t("meta.og.title") : pageTitle);
    setMeta("property", "og:description", page === "home" ? t("meta.og.description") : description);
    setMeta("property", "og:locale", active.ogLocale);
    setMeta("property", "og:url", `${origin}${route.path}`);
    setMeta("property", "og:site_name", t("meta.siteName"));

    // Alternate OG locales must not repeat the active one.
    clearManaged('meta[property="og:locale:alternate"]');
    for (const candidate of LOCALES) {
      if (candidate.code === active.code) continue;
      const tag = document.createElement("meta");
      tag.setAttribute("property", "og:locale:alternate");
      tag.setAttribute("content", candidate.ogLocale);
      tag.setAttribute("data-i18n-managed", "");
      document.head.appendChild(tag);
    }

    // Canonical + hreflang cluster. 404s are excluded: an error page must not
    // advertise itself as canonical content in nine languages.
    clearManaged("link");
    if (page !== "notFound") {
      addLink("canonical", `${origin}${pathFor(page, active.code)}`);
      for (const candidate of LOCALES) {
        addLink("alternate", `${origin}${pathFor(page, candidate.code)}`, candidate.htmlLang);
      }
      addLink("alternate", `${origin}${pathFor(page, DEFAULT_LOCALE)}`, "x-default");
    }

    // Document language and direction.
    document.documentElement.setAttribute("lang", active.htmlLang);
    document.documentElement.setAttribute("dir", active.dir);
    document.documentElement.dataset.dir = active.dir;
  });
}
